import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash, X509Certificate} from 'node:crypto';
import {
  base64UrlDecode,
  derToPem,
  hex,
  isCaCertificate,
  joinAddress,
  parseServerLink,
  pemToDer,
  shortFingerprint,
  splitAddress,
} from '../src/enrollment.ts';

const fixture = (name: string) => new Uint8Array(readFileSync(`${import.meta.dirname}/fixtures/${name}`));
const ca = fixture('ca.der');
const url64 = (bytes: Uint8Array) => Buffer.from(bytes).toString('base64url');
const link = (extra = '', cert = ca) =>
  `wasap://server?v=1&id=a2f1c0de-0000-4000-8000-000000000001&name=Redes%205.%C2%BA%20A&a=192.168.1.50%3A5050&a=10.8.0.1%3A5050${extra}&ca=${url64(cert)}`;

test('a valid link yields id, name, addresses in order and the CA as PEM', () => {
  const result = parseServerLink(link());
  assert.ok(result.ok);
  assert.equal(result.server.id, 'a2f1c0de-0000-4000-8000-000000000001');
  assert.equal(result.server.name, 'Redes 5.º A');
  assert.deepEqual(result.server.addresses, ['192.168.1.50:5050', '10.8.0.1:5050']);
  assert.deepEqual(result.server.caDer, ca);
  // Node parses the PEM we build: same certificate, same fingerprint.
  const parsed = new X509Certificate(result.server.caPem);
  assert.equal(parsed.fingerprint256.replace(/:/g, '').toLowerCase(), createHash('sha256').update(ca).digest('hex'));
  assert.deepEqual(pemToDer(result.server.caPem), ca);
});

test('foreign QR codes and other versions are rejected', () => {
  for (const text of ['https://example.com', 'WIFI:S:aula;T:WPA;P:x;;', 'wasap://chat?v=1', '']) {
    const result = parseServerLink(text);
    assert.equal(result.ok, false);
    assert.match((result as {reason: string}).reason, /No es un servidor Wasap compatible/);
  }
  const v2 = parseServerLink(link().replace('v=1', 'v=2'));
  assert.equal(v2.ok, false);
  assert.match((v2 as {reason: string}).reason, /Actualiza la app/);
});

test('only CA certificates are accepted as anchors', () => {
  assert.equal(isCaCertificate(ca), true);
  assert.equal(isCaCertificate(fixture('leaf.der')), false, 'basicConstraints CA:FALSE');
  assert.equal(isCaCertificate(fixture('plain.der')), false, 'no basicConstraints');
  assert.equal(isCaCertificate(ca.subarray(0, 100)), false, 'truncated');
  const leaf = parseServerLink(link('', fixture('leaf.der')));
  assert.equal(leaf.ok, false);
  assert.match((leaf as {reason: string}).reason, /no es el de una autoridad/);
  assert.equal(parseServerLink(link().replace(/ca=.*/, 'ca=@@@')).ok, false);
});

test('addresses must be host:port with 1 to 5 entries', () => {
  assert.deepEqual(splitAddress('[2001:db8::5]:5050'), {host: '2001:db8::5', port: 5050});
  assert.deepEqual(splitAddress('aula.local:6000'), {host: 'aula.local', port: 6000});
  assert.equal(splitAddress('10.0.0.1'), null);
  assert.equal(splitAddress('10.0.0.1:70000'), null);
  assert.equal(joinAddress('2001:db8::5', 5050), '[2001:db8::5]:5050');
  assert.equal(parseServerLink(link('&a=10.0.0.1%3A70000')).ok, false);
  const six = Array.from({length: 4}, (_, i) => `&a=10.0.1.${i}%3A5050`).join('');
  assert.equal(parseServerLink(link(six)).ok, false);
  const none = `wasap://server?v=1&id=x&name=n&ca=${url64(ca)}`;
  assert.equal(parseServerLink(none).ok, false);
});

test('base64 and fingerprint helpers', () => {
  assert.deepEqual(base64UrlDecode(url64(ca)), ca);
  assert.equal(derToPem(ca).split('\n')[1].length, 64);
  assert.equal(hex(Uint8Array.from([0, 15, 255])), '000fff');
  assert.equal(shortFingerprint('a1b2c3d4e5f60718ffff'), 'A1B2 C3D4 E5F6 0718');
});

test('a link generated by `wasap-server certs qr` parses with the same CA', () => {
  const result = parseServerLink(readFileSync(`${import.meta.dirname}/fixtures/server-link.txt`, 'utf8'));
  assert.ok(result.ok);
  assert.deepEqual(result.server.addresses, ['127.0.0.1:5050', 'aula.local:6000']);
  assert.equal(
    createHash('sha256').update(result.server.caDer).digest('hex'),
    'b4e980946fe4e422c382254c822aecd9e91b057fc46b90a5bec2072264a84236',
  );
});

test('invite and signup links carry the server plus their code', () => {
  const base = link().slice('wasap://server?'.length);
  const invite = parseServerLink(`wasap://invite?${base}&code=abcdefghjklmnpqrstuvwxyz23`);
  assert.ok(invite.ok);
  assert.equal(invite.kind, 'invite');
  assert.equal(invite.code, 'ABCDEFGHJKLMNPQRSTUVWXYZ23');
  assert.equal(invite.server.name, 'Redes 5.º A');
  const signup = parseServerLink(`wasap://signup?${base}&code=K7PX2M9Q&class=Redes%205A`);
  assert.ok(signup.ok);
  assert.equal(signup.kind, 'signup');
  assert.equal(signup.code, 'K7PX2M9Q');
  assert.equal(signup.className, 'Redes 5A');
  assert.equal(parseServerLink(`wasap://invite?${base}`).ok, false, 'an invite needs its code');
  assert.equal(parseServerLink(`wasap://signup?${base}&code=K7PX`).ok, false);
  const plain = parseServerLink(link());
  assert.ok(plain.ok);
  assert.equal(plain.kind, 'server');
});
